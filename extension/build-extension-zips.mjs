// Build the downloadable extension zip for every brand this repo ships.
//
//   node extension/build-extension-zips.mjs
//   → app/public/downloads/GOADS-Extension.zip
//   → app/public/downloads/ToolFB-Extension.zip
//
// One source tree, two packages. The extension is otherwise identical: only the
// name, site, support link, logo/icons and the GOADS-only tempmail feature
// differ, and all of that is driven from the BRAND block in content.js plus a
// handful of manifest fields — nothing here rewrites logic.
//
// Output archives are FLAT (manifest.json at the zip root, no wrapper folder):
// "Extract All" on Windows / double-click on macOS then produces a single
// <Brand>-Extension/ folder ready for chrome://extensions → Load unpacked.
//
// Replaces the old build-zip.sh, which was GOADS-only and needed the `zip` CLI
// that Windows/Git Bash doesn't ship — this falls back to PowerShell's
// Compress-Archive so the same command works on Windows and macOS.

import { execFileSync } from "node:child_process"
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const outDir = resolve(here, "../app/public/downloads")

// Files every build ships (the manifest references each one).
const BASE_FILES = ["background.js", "content.js", "content.css", "manifest.json", "inter-var.woff2"]

/**
 * Brand table — mirrors app/src/config/brand.ts (name / url / telegram). Kept
 * as plain data here because this script is plain Node and that config is TS;
 * when a brand changes there, change it here too.
 *
 * `brand` becomes the BRAND block inside content.js, verbatim.
 */
const BRANDS = [
  {
    key: "goads",
    zip: "GOADS-Extension.zip",
    // null → keep the icons/logo that sit in extension/ (the GOADS artwork).
    assets: null,
    manifest: {
      name: "GOADS Tools",
      description:
        "Business Manager Invitation & Session Manager — Professional Business Manager invitation and cookie-based authentication solution by GOADS Agency. goadsagency.com",
      actionTitle: "GOADS Tools",
    },
    brand: {
      name: "GOADS",
      productName: "GOADS Tools",
      site: "goadsagency.com",
      siteUrl: "https://goadsagency.com",
      telegram: "https://t.me/goads_official",
      logoFile: "goads-logo.png",
      tempmail: { enabled: true, domain: "goadsagency.com", url: "https://goadsagency.com/tempmail" },
    },
  },
  {
    key: "toolfb",
    zip: "ToolFB-Extension.zip",
    // ToolFB's own mark, generated from app/public/toolfb/icon.png.
    assets: { dir: "brands/toolfb", logo: "toolfb-logo.png" },
    manifest: {
      name: "ToolFB Tools",
      description:
        "Business Manager invitation & cookie session manager for Meta advertisers — invite by email and log in by cookie. toolfb.media",
      actionTitle: "ToolFB Tools",
    },
    brand: {
      name: "ToolFB",
      productName: "ToolFB Tools",
      site: "toolfb.media",
      siteUrl: "https://toolfb.media",
      // No support channel on the neutral brand → the footer link is dropped.
      telegram: "",
      logoFile: "toolfb-logo.png",
      // Tempmail is a goadsagency.com service; a neutral build hides it rather
      // than linking customers out to GOADS.
      tempmail: { enabled: false, domain: "", url: "" },
    },
  },
]

/** Swap the `/* BRAND:START *​/ … /* BRAND:END *​/` block in content.js. */
function withBrandBlock(source, brand) {
  const start = source.indexOf("/* BRAND:START")
  const endMark = "/* BRAND:END */"
  const end = source.indexOf(endMark)
  if (start < 0 || end < 0) throw new Error("content.js: BRAND:START/END markers not found")
  const head = source.slice(0, start)
  const tail = source.slice(end + endMark.length)
  const block =
    "/* BRAND:START — generated by build-extension-zips.mjs; edit the brand table\n" +
    "     there, not here. */\n" +
    "  const BRAND = " +
    JSON.stringify(brand, null, 2).split("\n").join("\n  ") +
    ";\n  " +
    endMark
  return head + block + tail
}

function zipDir(dir, outFile, files) {
  rmSync(outFile, { force: true })
  try {
    // No shell, no globs — the exact file list, so nothing is quoted wrong.
    execFileSync("zip", ["-j", "-q", outFile, ...files.map((f) => join(dir, f))], { stdio: "pipe" })
    return "zip"
  } catch {
    // Windows / no zip CLI — PowerShell ships Compress-Archive, and `dir\*`
    // keeps the archive flat just like `zip -j`.
    execFileSync(
      "powershell",
      ["-NoProfile", "-Command", `Compress-Archive -Path '${dir}\\*' -DestinationPath '${outFile}' -Force`],
      { stdio: "pipe" },
    )
    return "Compress-Archive"
  }
}

mkdirSync(outDir, { recursive: true })

for (const b of BRANDS) {
  const stage = mkdtempSync(join(tmpdir(), `ext-${b.key}-`))
  try {
    for (const f of BASE_FILES) cpSync(join(here, f), join(stage, f))

    // Icons + logo: the brand's own artwork when it has some, else the GOADS set.
    const logoName = b.brand.logoFile
    if (b.assets) {
      for (const s of [16, 32, 48, 128]) {
        cpSync(join(here, b.assets.dir, `icon${s}.png`), join(stage, `icon${s}.png`))
      }
      cpSync(join(here, b.assets.dir, "logo.png"), join(stage, logoName))
    } else {
      for (const s of [16, 32, 48, 128]) cpSync(join(here, `icon${s}.png`), join(stage, `icon${s}.png`))
      cpSync(join(here, logoName), join(stage, logoName))
    }

    // content.js — brand block.
    writeFileSync(join(stage, "content.js"), withBrandBlock(readFileSync(join(here, "content.js"), "utf8"), b.brand))

    // manifest.json — name/description/title + the logo's web-accessible name.
    const manifest = JSON.parse(readFileSync(join(here, "manifest.json"), "utf8"))
    manifest.name = b.manifest.name
    manifest.description = b.manifest.description
    manifest.action.default_title = b.manifest.actionTitle
    manifest.web_accessible_resources[0].resources = [logoName, "inter-var.woff2"]
    writeFileSync(join(stage, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n")

    const out = join(outDir, b.zip)
    const via = zipDir(stage, out, [...BASE_FILES, logoName, "icon16.png", "icon32.png", "icon48.png", "icon128.png"])
    console.log(`Built: ${out}  (${b.manifest.name}, via ${via})`)
  } finally {
    rmSync(stage, { recursive: true, force: true })
  }
}
